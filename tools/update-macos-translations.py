"""Collect paired native UI strings without translating editable user data."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
pairs=set()
for path in sorted((ROOT/"macos").glob("*.m")):
    pairs.update(re.findall(r'@?"((?:[^"\\]|\\.)*)"\s*,\s*@?"((?:[^"\\]|\\.)*)"',path.read_text(encoding="utf8")))
# Only Russian/English text pairs, excluding action/metadata pairs.
pairs={p for p in pairs if re.search('[А-Яа-яЁё]',p[1]) and not re.search('[А-Яа-яЁё]',p[0])}
(ROOT/"macos/translations.h").write_text("/* Generated by tools/update-macos-translations.py. */\n"+"".join('{"%s","%s"},\n'%p for p in sorted(pairs)),encoding="utf8")

"""Generate code-page-independent C literals from the editable UTF-8 catalog."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
catalog = json.loads((root / "locale/ru.json").read_text(encoding="utf-8"))

def literal(text):
    return '"' + ''.join(
        chr(c) if 32 <= c < 127 and c not in (34, 92) else f'\\{c:03o}'
        for c in text.encode("utf-8")) + '"'

output = "/* Generated by tools/generate-translations.py; edit locale/ru.json. */\n"
output += ''.join(f"    {{{literal(en.replace('&', ''))}, {literal(ru)}}},\n" for en, ru in catalog.items())
(root / "windows/kittyrus-translations.h").write_text(output, encoding="ascii")
print(f"Generated {len(catalog)} translations")

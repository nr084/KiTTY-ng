"""Generate code-page-independent C literals from the editable UTF-8 catalog."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
catalog = json.loads((root / "locale/ru.json").read_text(encoding="utf-8"))

def literal(text):
    return '"' + ''.join(
        chr(c) if 32 <= c < 127 and c not in (34, 92) else f'\\{c:03o}'
        for c in text.encode("utf-8")) + '"'

output = "/* Generated by tools/generate-translations.py; edit locale/ru.json. */\n"
output += ''.join(f"    {{{literal(en.replace('&', ''))}, {literal(ru)}}},\n" for en, ru in catalog.items())
(root / "windows/kittyng-translations.h").write_text(output, encoding="ascii")
print(f"Generated {len(catalog)} translations")

# Platform overrides preserve context-specific wording, not separate engines.
contexts = json.loads((root / "locale/ru-contexts.json").read_text(encoding="utf-8"))
data = "/* Generated; edit locale/ru.json and locale/ru-contexts.json. */\n"
def table(name, entries):
    pairs = sorted(entries.items(), key=lambda pair: pair[0].encode("utf-8"))
    return "static const KrMessage " + name + "[] = {\n" + "".join(
        "    {" + literal(k) + ", " + literal(v) + "},\n" for k, v in pairs
    ) + "};\n"
data += table("common_messages", catalog)
for name in ("linux", "macos-cli", "macos-ui"):
    data += table(name.replace('-', '_') + "_messages", contexts[name])
(root / "locale/builtin.h").write_text(data, encoding="ascii")

for legacy in ("translations.h", "error-translations.h", "cli-extra-translations.h"):
    (root / "macos" / legacy).write_text('/* Compatibility include; catalog lives in locale/ru.json. */\n#include "../windows/kittyng-translations.h"\n', encoding="ascii")

typedef struct {double x1,y1,x2,y2,width;} KrMacLine;
static int kr_mac_box_lines(unsigned ch,double w,double h,double scale,KrMacLine *out){
    if(ch<0x2500||ch>0x257f||w<=0||h<=0||scale<=0)return 0;
    KrMacBox b=kr_mac_boxes[ch-0x2500];int n=0;
    if(b.diagonal){if(b.diagonal&1)out[n++]=(KrMacLine){0,h,w,0,1/scale};if(b.diagonal&2)out[n++]=(KrMacLine){0,0,w,h,1/scale};return n;}
    for(int arm=0;arm<4;arm++){
        unsigned style=(b.arms>>(arm*2))&3;if(!style)continue;
        double weight=(style==2?2:1)/scale;
        double cx=(floor(w*scale/2)+(style==2?0:.5))/scale,cy=(floor(h*scale/2)+(style==2?0:.5))/scale;
        int copies=style==3?2:1;
        for(int lane=0;lane<copies;lane++){
            double offset=copies==2?(lane?1:-1)*2/scale:0;
            double x1=cx,y1=cy,x2,y2;
            if(arm==0||arm==2){x1=x2=cx+offset;y2=arm==0?0:h;
                unsigned east=(b.arms>>2)&3,west=(b.arms>>6)&3;
                if(copies==2&&((east==3) != (west==3)))y1+=offset*(arm==2?1:-1)*(east==3?1:-1);
            }else{y1=y2=cy+offset;x2=arm==1?w:0;
                unsigned north=b.arms&3,south=(b.arms>>4)&3;
                if(copies==2&&((north==3) != (south==3)))x1+=offset*(arm==1?1:-1)*(south==3?1:-1);
            }
            out[n++]=(KrMacLine){x1,y1,x2,y2,weight};
        }
    }
    return n;
}
